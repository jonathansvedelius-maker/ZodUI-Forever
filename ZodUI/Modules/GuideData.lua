-- Routes through dungeons for the Dungeon guide (Modules\Guide.lua).
--
-- A floor is the client's own dungeon map: Interface\WorldMap\<Name>\<Name><n>_1..12, a 4x3 grid of
-- 256px tiles of which the top-left 1002x668 is the map. `map` is its uiMapID, which the game reports
-- for you inside the dungeon (C_Map.GetBestMapForUnit), so the guide turns to your floor by itself.
--
-- A step is a place to go: `floor`, `x`, `y` (fractions of the 1002x668 map), a title and one line of
-- help. `boss` lists its encounter IDs (ENCOUNTER_END/BOSS_KILL; each boss has an old and a newer ID),
-- and `name` is matched too, so a kill moves the guide past it. `via` are bends in the line from the
-- step before. A step without x and y has no known spot yet: the guide says so, and the draw mode
-- places it. `optional` steps are rares or side bosses the route passes.
--
-- Wings: dungeons that share one instance (the four Scarlet Monastery wings) name their `group`. The
-- game does not always tell them apart from inside, so the guide asks the floor's map ID first, then
-- `rooms` (sub-zone names, lower case), then which boss died, then the wing you picked.
--
-- Shadowfang Keep: floors and boss pins as ForeverDungeonJournal 2.0.11 shows them (its Core\Journal.lua,
-- the pins from the boss positions published for the Forever client), encounter IDs from its
-- Data\RunLogEncounters.lua. The path between the pins is drawn from the classic route; its bends are
-- approximate. Commander Springvale has no published spot, so he has none here.

